def is_language(name):
    """Is this the name of a language ("Spanish", "español", "Chinese (Simplified)")?"""
    n = re.sub(r"\s*\([^)]*\)\s*$", "", str(name or "").strip().lower())
    return n in LANGUAGE_NAMES or str(name or "").strip().lower() in LANGUAGE_NAMES


def _placeholders(text):
    return set(re.findall(r"\{(\w+)\}", str(text)))


def lang_code(name):
    n = (name or "").strip().lower()
    if n in _ALIAS:
        return _ALIAS[n]
    return re.sub(r"[^a-z0-9À-￿]+", "-", n).strip("-") or "en"


def display_name(name):
    code = lang_code(name)
    return {"en": "English", "zh": "中文", "es": "Español", "fr": "Français",
            "de": "Deutsch", "ja": "日本語"}.get(code, name.strip().title())


_cache = {}


def _generated(code, name):
    """Translate the English table with the on-device model, once."""
    path = os.path.join(config.ETC, "i18n", code + ".json")
    table = config.load_json(path, None)
    if table and set(EN) <= set(table):
        return table
    try:
        from . import llm
        keys = list(EN)
        table = llm.translate_strings({k: EN[k] for k in keys}, name)
        if table and all(isinstance(table.get(k), str) and table[k].strip() for k in keys):
            # a translation that renamed or dropped a {placeholder} would crash the screen that uses it:
            # those few strings stay in English
            table = {k: (table[k] if _placeholders(table[k]) == _placeholders(EN[k]) else EN[k]) for k in keys}
            config.save_json(path, table, mode=0o644)
            return table
    except Exception:
        pass
    return None


_failed = {}


def table_for(language):
    """The table for a language. A generation that failed (the model was
    not up yet) is retried later, not remembered as a failure."""
    code = lang_code(language)
    if code in BUILTIN:
        return BUILTIN[code]
    if code not in _cache:
        if time.time() - _failed.get(code, 0) > 30:
            table = _generated(code, language)
            if table:
                _cache[code] = table
            else:
                _failed[code] = time.time()
    return _cache.get(code) or EN


def t(key, area=None, **fmt):
    s = table_for(config.llm_language(area)).get(key) or EN.get(key, key)
    if not fmt:
        return s
    try:
        return s.format(**fmt)
    except (KeyError, IndexError, ValueError):     # a stored translation with a broken placeholder: English
        return EN.get(key, key).format(**fmt)
